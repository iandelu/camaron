"""WorkspaceStore: what the app asks of the project's workspace.yaml (the repos that form the project, the interview
mode, which repos get a wiki) and of the block in cam-docs' .gitignore that follows those repos."""
from __future__ import annotations

from pathlib import Path
from typing import Protocol


class WorkspaceStore(Protocol):
    WS_HEADER: str

    def workspace(self) -> dict: ...

    def save_workspace(self, ws: dict) -> None: ...

    def write_workspace(self, ws_file: Path, ws: dict) -> None: ...

    def repo_names(self) -> list[str]: ...

    def wiki_repos(self) -> list[str]: ...

    def interview_mode(self) -> str: ...

    def interview_mode_chosen(self) -> bool: ...

    def set_interview_mode(self, mode: str) -> None: ...

    def set_wiki_repos(self, names: list[str]) -> None: ...

    def write_gitignore(self) -> None: ...
